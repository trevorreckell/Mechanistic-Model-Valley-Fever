function [X, y, pop] = tc_design(r, t_inf, t_pop, nMonths, nLagHist)
% Tamerius-Comrie design matrix: mean temperature (C), PM10, and
% precipitation lagged 18 and 24 months. The climate series carry nLagHist
% months of pre-2013 history so both lags are real observations, not zeros.
    Pmm  = r.Precip(:) * 25.4;
    TC   = (r.Temp(:) - 32) * (5/9);
    PM   = r.PM10(:);
    L18  = [zeros(18,1); Pmm(1:end-18)];
    L24  = [zeros(24,1); Pmm(1:end-24)];
    vi   = (nLagHist+1) : numel(Pmm);
    Xall = [TC(vi), PM(vi), L18(vi), L24(vi)];
    X    = Xall(1:nMonths, :);
    y    = r.Cases(:);   y = y(1:nMonths);
    popA = interp1(t_pop, r.PopRaw(:), t_inf, 'linear', 'extrap');
    pop  = popA(1:nMonths);
end


function [yhat, k] = tc_fit_predict(Xtr, ytr, popTr, Xte, popTe, form)
% Fit on the training rows, predict CASE COUNTS for the test rows.
% k counts estimated coefficients only; the variance is not counted, which
% matches how k is defined for the ODE models.
    switch lower(form)
    case 'ols_rate'
        rate = (ytr ./ popTr) * 100000;
        mdl  = fitlm(Xtr, rate);
        pr   = max(0, predict(mdl, Xte));
        yhat = (pr / 100000) .* popTe;
        k    = mdl.NumCoefficients;
    case 'poisson_glm'
        b    = glmfit(Xtr, round(ytr), 'poisson', 'link', 'log', ...
                      'Offset', log(popTr));
        yhat = exp([ones(size(Xte,1),1) Xte] * b + log(popTe));
        k    = numel(b);
    otherwise
        error('MODEL_FORM must be ''ols_rate'' or ''poisson_glm''');
    end
    yhat = yhat(:);
end