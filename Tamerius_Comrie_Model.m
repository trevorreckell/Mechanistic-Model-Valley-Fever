%  Tamerius & Comrie statistical baseline for Valley fever incidence,
%  rewritten so every metric is directly comparable to the Model 4b (M5)
%  mechanistic ODE fitting and forecasting paths.
%
%  WHAT IS COMPARABLE (and was not before)
%    RRMSE      mean-normalised, sqrt(mean(r.^2))/mean(y), on MONTHLY CASE
%               COUNTS over 132 months. The previous version divided by
%               sqrt(sum(y.^2)), which is RRMSE/sqrt(n) -- about 12.3x too
%               small. Old 2.7% for Maricopa is really 32.8%.
%    n          132 monthly intervals, matching M5 (was 133).
%    AIC/AICc/BIC  computed from RSS on the CASE scale. The previous version
%               used mdl.SSE, which is on the incidence-RATE scale (per
%               100,000) and differs by ~1000 units, so it could not be
%               compared with M5's case-scale AIC at all.
%    horizons   fit 96 / 108 / 120 months, forecast the next 12. These are
%               exactly M5's windows and correspond to calendar 2021/2022/2023.
%    baselines  persistence, seasonal naive and train-mean on the same 12
%               months, plus the empirical noise floor, so a number can be
%               judged rather than just reported.
%    saves      region-tagged .mat files, so multiple regions can run at once
%               without collision, mirroring the M5 naming scheme.
%    residuals  per-month forecast residuals are saved to enable a
%               Diebold-Mariano test against the ODE models later.
%
%  REGION INDEXING now matches Model 5:  1 = AZ, 2 = Maricopa, 3 = Pima,
%  4 = Pinal. The old script used a different order.
%
%  MODEL FORM
%    'ols_rate'     OLS on incidence per 100,000, four predictors:
%                   mean temperature (C), PM10, precipitation lagged 18 and
%                   24 months. This is the form the previous script fitted
%                   and is the default so results stay continuous.
%    'poisson_glm'  Poisson GLM on counts with log(population) offset. More
%                   appropriate for count data and what the old header
%                   claimed ("Poisson GLM") while the code ran fitlm.
%                   Reported AIC still uses the Gaussian-RSS form on cases so
%                   it stays comparable to M5.
% ========================================================================

